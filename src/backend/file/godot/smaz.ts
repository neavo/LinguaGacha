/** OptimizedTranslation 使用 Smaz，解码长度包含消息末尾 NUL。 */
export function smaz_decode(bytes: Buffer, size: number): Buffer {
  assert(size >= 0 && size <= GODOT_RESOURCE_MAX_BYTES);
  const out = Buffer.alloc(size);
  let at = 0,
    pos = 0;
  const put = (b: Buffer) => {
    assert(pos + b.length <= size, "Smaz overflow");
    out.set(b, pos);
    pos += b.length;
  };
  while (at < bytes.length) {
    const c = bytes[at++]!;
    if (c < 254) put(Buffer.from(codebook[c]!));
    else if (c === 254) {
      assert(at < bytes.length);
      put(bytes.subarray(at, ++at));
    } else {
      assert(at < bytes.length);
      const n = bytes[at++]! + 1;
      assert(at + n <= bytes.length);
      put(bytes.subarray(at, at + n));
      at += n;
    }
  }
  assert.equal(pos, size);
  return out;
}
